"""The end-of-engagement report (2026-11-05).

Reads from the rows database (facts, findings, coverage, exchanges) —
NOT from the model's last message or free-text notes. The report IS
the data. A professional can read it, submit it, or hand it to a client.

Saved to <engagement>/report.md AND printed to console.
"""

from __future__ import annotations

import contextlib
import json
import time
from pathlib import Path


def generate_report(engagement_dir: Path | str) -> str:
    """Generate the markdown report from the engagement's stored data."""
    eng = Path(engagement_dir)
    from suijin.modules.platform.lib.workspace import WORKSPACE_DIR

    _ws = Path(WORKSPACE_DIR)
    del _ws  # workspace not needed; engagement_dir is explicit

    target = _target_from_dirname(eng.name)
    started = _trail_started(eng)
    ended = _trail_ended(eng)
    duration = _duration_s(started, ended)
    cost = _trail_cost(eng)
    iterations = _trail_iterations(eng)

    lines = []
    lines.append(f"# Engagement Report — {target}")
    lines.append(
        f"**Duration:** {_fmt_duration(duration)} · **Iterations:** {iterations or '?'} · **Cost:** ${cost:.2f}"
    )
    if started:
        lines.append(f"**Started:** {started}")
    lines.append("")

    # ── Findings ──
    findings = _read_findings(eng)
    if findings:
        lines.append("## Findings")
        lines.append("")
        for f in findings:
            _render_finding(lines, f)
    else:
        lines.append("## Findings")
        lines.append("")
        lines.append("_No confirmed findings this engagement._")

    # ── Coverage ──
    coverage = _read_coverage(eng)
    if coverage:
        lines.append("## Coverage Summary")
        lines.append("")
        lines.append("| Class | Tested | Found | Coverage |")
        lines.append("|-------|--------|-------|----------|")
        for cls, stats in sorted(coverage.items()):
            bar = "█" * int(stats["pct"] / 10) + "░" * (10 - int(stats["pct"] / 10))
            lines.append(f"| {cls} | {stats['tested']} cells | {stats['found']} | {bar} {stats['pct']:.0f}% |")
        lines.append("")

    # ── Facts / Methodology ──
    facts = _read_facts(eng)
    if facts:
        lines.append("## Methodology")
        lines.append("")
        for f in facts[-20:]:
            tag = "observed" if f.get("observed") else "inferred"
            summary = str(f.get("summary") or "")[:120]
            lines.append(f"- [{tag}] {summary}")
        lines.append("")

    # ── Traffic Summary ──
    traffic_count = _count_exchanges(eng)
    if traffic_count:
        lines.append("## Recorded Traffic")
        lines.append("")
        lines.append(f"- {traffic_count} HTTP exchanges recorded in `traffic/index.db`")
        lines.append(f'- Search with `traffic_search(host="{target}")` or query the database directly')
        lines.append("")

    # ── Artifacts ──
    lines.append("## Artifacts")
    lines.append("")
    if (eng / "exploits").is_dir():
        exps = sorted((eng / "exploits").glob("*/"))
        if exps:
            lines.append(f"- POC scripts: {', '.join(e.name for e in exps[:10])}")
    if (eng / "audit_trails").is_dir():
        lines.append("- Full audit trail: `audit_trails/`")
    if (eng / "state" / "rows").is_dir():
        lines.append("- Structured data (facts, assets, intents): `state/rows/`")
    lines.append("")

    lines.append("---")
    lines.append(f"_Generated by Suijin at {time.strftime('%Y-%m-%d %H:%M UTC', time.gmtime())}_")

    report = "\n".join(lines)
    out = eng / "report.md"
    with contextlib.suppress(OSError):
        out.write_text(report, encoding="utf-8")
    return report


def _target_from_dirname(name: str) -> str:
    parts = name.split("_", 2)
    raw = parts[2] if len(parts) >= 3 else name
    # 127.0.0.1_6000 → 127.0.0.1:6000 (the port separator)
    import re as _re

    return _re.sub(r"_(\d+)$", r":\1", raw) if _re.search(r"\.\d+_\d+$", raw) else raw


def _trail_json(eng: Path) -> dict:
    for f in (eng / "audit_trails").glob("*.json"):
        if f.name.startswith("agent_steps"):
            continue
        with contextlib.suppress(Exception):
            return json.loads(f.read_text())
    return {}


def _trail_started(eng: Path) -> str:
    return str(_trail_json(eng).get("started") or "")


def _trail_ended(eng: Path) -> str:
    trail = _trail_json(eng)
    ended = str(trail.get("ended") or "")
    if ended:
        return ended
    # estimate from the last event file's mtime (pre-rows engagements
    # that never cleanly ended)
    ev = eng / "events.jsonl"
    if ev.is_file():
        with contextlib.suppress(OSError):
            return time.strftime("%Y-%m-%dT%H:%M:%S+00:00", time.gmtime(ev.stat().st_mtime))
    return ""


def _trail_cost(eng: Path) -> float:
    return float(_trail_json(eng).get("cost_usd") or 0)


def _trail_iterations(eng: Path) -> int:
    return int(_trail_json(eng).get("iterations") and len(_trail_json(eng).get("iterations", [])) or 0)


def _duration_s(started: str, ended: str) -> float:
    with contextlib.suppress(Exception):
        from datetime import datetime, timezone

        s = datetime.fromisoformat(started.replace("Z", "+00:00"))
        e = datetime.fromisoformat(ended.replace("Z", "+00:00")) if ended else datetime.now(timezone.utc)
        return (e - s).total_seconds()
    return 0


def _fmt_duration(s: float) -> str:
    if s < 60:
        return f"{s:.0f}s"
    if s < 3600:
        return f"{s / 60:.0f}m {s % 60:.0f}s"
    return f"{s / 3600:.0f}h {(s % 3600) / 60:.0f}m"


def _read_findings(eng: Path) -> list[dict]:
    """Findings from the rows database OR the exploit catalog OR the
    audit trail's findings array (pre-rows engagements)."""
    out = []
    # 1. rows database (wall-memo slice 2)
    rows_f = eng / "state" / "rows" / "finding.jsonl"
    if rows_f.is_file():
        with contextlib.suppress(Exception):
            for ln in rows_f.read_text(errors="replace").splitlines():
                if ln.strip():
                    out.append(json.loads(ln))
    # 2. exploit catalog (the POC-backed entries)
    for md in sorted((eng / "exploits").glob("*/EXP-*/description.md")):
        with contextlib.suppress(Exception):
            text = md.read_text(errors="replace")
            out.append(
                {
                    "title": _extract_field(text, "title") or md.parent.name,
                    "status": "confirmed" if "CONFIRMED" in text else "pending",
                    "severity": _extract_field(text, "severity") or "—",
                    "class": _extract_field(text, "class") or "—",
                    "target": _extract_field(text, "target") or "",
                    "poc_path": str(md.parent),
                }
            )
    # 3. audit trail findings (pre-rows engagements)
    trail = _trail_json(eng)
    for f in trail.get("findings") or []:
        if isinstance(f, dict):
            ftype = str(f.get("type") or f.get("class") or "finding")
            endpoint = str(f.get("endpoint") or f.get("target") or "")
            if ftype == "credential":
                continue  # credentials don't go in the report body
            out.append(
                {
                    "title": f"{ftype}: {endpoint}" if endpoint else ftype,
                    "status": "confirmed",
                    "severity": "info",
                    "class": ftype,
                    "target": endpoint,
                }
            )
    return out


def _extract_field(text: str, field: str) -> str:
    import re

    m = re.search(rf"{field}\s*\(*[A-Z]*\)*\s*:\s*\**\*?([^*\n]+)", text)
    return m.group(1).strip() if m else ""


def _render_finding(lines: list, f: dict) -> None:
    status = str(f.get("status") or "pending")
    sev = str(f.get("severity") or "—")
    title = str(f.get("title") or "—")
    target = str(f.get("target") or "")
    vuln_class = str(f.get("class") or "")
    poc = str(f.get("poc_path") or "")

    lines.append(f"### {title} ({sev.upper()})")
    lines.append(f"**Status:** {status}")
    if target:
        lines.append(f"**Target:** {target}")
    if vuln_class:
        lines.append(f"**Class:** {vuln_class}")
    if poc:
        lines.append(f"**POC:** `{poc}`")
    lines.append("")

    # evidence from exchanges
    ex_ids = str(f.get("exchange_ids") or "")
    if ex_ids and ex_ids != "none":
        lines.append("**Evidence exchanges:** " + ex_ids)
    lines.append("")


def _read_coverage(eng: Path) -> dict:
    """Coverage summary from the cells or the database."""
    out = {}
    with contextlib.suppress(Exception):
        cov_f = eng / "state" / "coverage.json"
        if cov_f.is_file():
            data = json.loads(cov_f.read_text())
            cells = data.get("cells", {})
            by_class: dict[str, dict] = {}
            for key, cell in cells.items():
                cls = key.split("|")[-1] if "|" in key else "?"
                if cls not in by_class:
                    by_class[cls] = {"tested": 0, "found": 0, "total": 0, "vuln": 0}
                by_class[cls]["tested"] += 1
                by_class[cls]["total"] += 1
                if "vulnerab" in str(cell.get("status", "")):
                    by_class[cls]["vuln"] += 1
            for cls, stats in by_class.items():
                stats["pct"] = min(100, stats["tested"] / max(1, stats["total"]) * 100)
                stats["found"] = stats["vuln"]
                out[cls] = stats
    return out


def _read_facts(eng: Path) -> list[dict]:
    facts_f = eng / "state" / "rows" / "fact.jsonl"
    if not facts_f.is_file():
        return []
    with contextlib.suppress(Exception):
        return [json.loads(ln) for ln in facts_f.read_text(errors="replace").splitlines() if ln.strip()]
    return []


def _count_exchanges(eng: Path) -> int:
    import sqlite3

    db = eng / "state" / "traffic" / "index.db"
    if not db.is_file():
        return 0
    with contextlib.suppress(sqlite3.Error), sqlite3.connect(str(db)) as c:
        return int(c.execute("SELECT COUNT(*) FROM exchange").fetchone()[0])
    return 0
